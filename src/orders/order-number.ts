/** Номер замовлення 1С: 0000-066717. */
const ORDER_NUMBER = /(?<!\d)\d{4}-\d{6}(?!\d)/;

/**
 * Витягує номер 1С із того, що прислав сервіс-джерело: "№А 0000-066717" → "0000-066717"
 * (у призначенні платежу перед номером буває літера А/Д/Т/Р). Нестандартний номер
 * повертається як є, лише без пробілів на краях.
 */
export function normalizeOrderNumber(raw: string): string {
  return ORDER_NUMBER.exec(raw)?.[0] ?? raw.trim();
}
